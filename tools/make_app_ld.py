#!/usr/bin/env python3
"""
make_app_ld.py - derive an APPLICATION linker script for the cutcutgo-bl
bootloader from the stock PIC32MK1024MCF100 linker script.

  python make_app_ld.py <stock p32MK1024MCF100.ld> <output app.ld>

Layout of an application:
  0x9D010000  reset/startup code (the bootloader jumps here)
  0x9D011000  exception base (EBASE) and program code
  ..0x9D0FD000  end of application (the last 3 pages are kept free for the
               test marker and the diagnostic bootloader's pages)
Real applications can use the same script; only the end address matters if
you don't use the diagnostic builds.
"""
import sys

REPLACEMENTS = [
    ("PROVIDE(_ebase_address = 0x9D000000);", "PROVIDE(_ebase_address = 0x9D011000);"),
    ("_RESET_ADDR                    = 0xBFC00000;", "_RESET_ADDR                    = 0x9D010000;"),
    ("_BEV_EXCPT_ADDR                = 0xBFC00380;", "_BEV_EXCPT_ADDR                = 0x9D010380;"),
    ("kseg0_program_mem     (rx)  : ORIGIN = 0x9D000000, LENGTH = 0x100000",
     "kseg0_program_mem     (rx)  : ORIGIN = 0x9D011000, LENGTH = 0xEC000"),
    ("kseg1_boot_mem              : ORIGIN = 0xBFC00000, LENGTH = 0x480",
     "kseg1_boot_mem              : ORIGIN = 0x9D010000, LENGTH = 0x480"),
]


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src, newline="").read()
    for old, new in REPLACEMENTS:
        if text.count(old) != 1:
            raise SystemExit("expected exactly one '%s' in %s" % (old, src))
        text = text.replace(old, new)
    header = ("/* Generated by make_app_ld.py from %s:\n"
              " * application for the cutcutgo-bl bootloader, entry at 0x9D010000. */\n" % src)
    open(dst, "w", newline="").write(header + text)


if __name__ == "__main__":
    main()
